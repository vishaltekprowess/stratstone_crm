from odoo import models, fields, api


class AttendanceLocation(models.Model):
    _name = 'attendance.location'
    _description = 'Attendance Location Data'
    _order = 'timestamp desc'

    attendance_id = fields.Many2one(
        'hr.attendance',
        string='Attendance',
        required=True,
        ondelete='cascade',
        index=True,
    )
    employee_id = fields.Many2one(
        'hr.employee',
        string='Employee',
        required=True,
        ondelete='cascade',
        index=True,
    )
    location_type = fields.Selection(
        [('check_in', 'Check In'), ('check_out', 'Check Out'), ('tracking', 'Tracking')],
        string='Type',
        required=True,
    )
    latitude = fields.Float(
        string='Latitude',
        digits=(10, 7),
    )
    longitude = fields.Float(
        string='Longitude',
        digits=(10, 7),
    )
    accuracy = fields.Float(
        string='Accuracy (m)',
        help='GPS accuracy in meters',
    )
    address = fields.Char(
        string='Address',
        help='Reverse-geocoded or client-provided address',
    )
    timestamp = fields.Datetime(
        string='Timestamp',
        default=fields.Datetime.now,
        required=True,
    )
    is_auto_checkout = fields.Boolean(
        string='Auto Check-Out',
        default=False,
        help='True if this location was generated by the auto check-out cron',
    )

    def action_open_map(self):
        """Open Google Maps at the recorded coordinates."""
        self.ensure_one()
        return {
            'type': 'ir.actions.act_url',
            'url': 'https://maps.google.com?q=%s,%s' % (self.latitude, self.longitude),
            'target': 'new',
        }
